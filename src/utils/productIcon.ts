const CATEGORY_ICONS: Partial<Record<ProductCategory, string>> = {
  Kiryana: 'store',
  Grocery: 'cart',
  Beverages: 'cup',
  Dairy: 'cow',
  Snacks: 'popcorn',
  Spices: 'chili-hot',
  'Personal Care': 'lotion',
  Bakery: 'bread-slice',
  Others: 'shopping',
};

export function productIconFor(name: string, category?: ProductCategory): string {
  const n = (name || '').toLowerCase();
  for (const [keywords, icon] of ITEM_RULES) {
    if (keywords.some((k) => n.includes(k))) return icon;
  }
  if (category && CATEGORY_ICONS[category]) return CATEGORY_ICONS[category]!;
  return 'shopping';
}
